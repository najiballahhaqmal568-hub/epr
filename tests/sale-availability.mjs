// Isolated browser, synthetic inventory, all external requests blocked.
import assert from 'node:assert/strict'
import { spawn } from 'node:child_process'
import { chromium } from 'playwright-core'
const url = 'http://localhost:5195/sale-availability'
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--port', '5195', '--strictPort'], { stdio: 'ignore' })
let browser
try {
  for (let i = 0; i < 60; i++) { try { if ((await fetch(url)).ok) break } catch {} await new Promise(r => setTimeout(r, 500)) }
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  const browserErrors = []
  page.on('pageerror', error => browserErrors.push(error.message))
  await page.route('**/*', route => {
    const request = new URL(route.request().url())
    if (!['localhost', '127.0.0.1'].includes(request.hostname)) return route.abort()
    if (request.pathname === '/src/main.tsx') return route.fulfill({ contentType: 'application/javascript', body: 'import "/src/index.css";' })
    return route.continue()
  })
  await page.goto(url)
  await page.evaluate(async () => {
    const { db } = await import('/src/db.ts')
    const { default: React } = await import('/node_modules/.vite/deps/react.js')
    const { default: ReactDOM } = await import('/node_modules/.vite/deps/react-dom_client.js')
    const { default: Sale } = await import('/src/pages/sales/NewSaleModal.tsx')
    const productId = await db.products.add({ name: 'بوت آزمایشی', createdAt: Date.now(), carton: { items: [{ size: '39', color: 'سیاه', qty: 2 }, { size: '40', color: 'سیاه', qty: 2 }] } })
    window.v1 = await db.variants.add({ productId, size: '39', color: 'سیاه', stockQty: 5, purchasePrice: 50, retailPrice: 100, wholesalePrice: 80 })
    window.v2 = await db.variants.add({ productId, size: '40', color: 'سیاه', stockQty: 4, purchasePrice: 50, retailPrice: 100, wholesalePrice: 80 })
    window.stock = async () => (await db.variants.toArray()).map(v => v.stockQty)
    ReactDOM.createRoot(document.getElementById('root')).render(React.createElement(Sale, { embedded: true, onClose() {}, draft: { id: 'test', saleType: 'wholesale', lines: [{ variantId: window.v1, productName: 'بوت آزمایشی', size: '39', color: 'سیاه', qty: 2, unitPrice: 80 }] } }))
  })
  const qty = page.getByRole('textbox', { name: 'تعداد بوت آزمایشی 39', exact: true })
  await qty.waitFor()
  await page.getByText(/موجودی: ۵.*انتخاب‌شده: ۲.*باقی‌مانده: ۳/).first().waitFor({ timeout: 5000 })
  await qty.fill('5')
  await page.getByText('تمام موجودی انتخاب شد', { exact: true }).first().waitFor()
  assert.equal(await page.getByRole('button', { name: 'افزایش تعداد بوت آزمایشی', exact: true }).isDisabled(), true)
  await qty.fill('6')
  await page.getByText(/۱ جوره بیشتر از موجودی/).first().waitFor()
  assert.equal(await page.getByRole('button', { name: 'ثبت فروش', exact: true }).isDisabled(), true)
  assert.deepEqual(await page.evaluate(() => window.stock()), [5, 4], 'selection never changes stock')
  await qty.fill('1.5')
  await page.getByText('تعداد باید عدد صحیح باشد', { exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'ثبت فروش', exact: true }).isDisabled(), true)
  await qty.fill('4')
  assert.equal(await page.getByRole('button', { name: 'ثبت فروش', exact: true }).isEnabled(), true)
  // Half-carton choices must subtract the four pairs already in the cart.
  await page.getByRole('button', { name: /بوت آزمایشی/ }).filter({ has: page.locator('p') }).first().click()
  await page.getByRole('button', { name: /نیم کارتن/ }).click()
  const half = page.getByRole('dialog')
  await half.getByRole('textbox', { name: 'تعداد نیم کارتن 39 سیاه', exact: true }).fill('2')
  await half.getByText(/۱ جوره بیشتر از موجودی/).waitFor()
  assert.equal(await half.getByRole('button', { name: /افزودن نیم کارتن/ }).isDisabled(), true)
  await half.getByRole('textbox', { name: 'تعداد نیم کارتن 39 سیاه', exact: true }).fill('1')
  await half.getByRole('textbox', { name: 'تعداد نیم کارتن 40 سیاه', exact: true }).fill('1')
  await half.getByRole('button', { name: /افزودن نیم کارتن/ }).click()
  assert.equal(await qty.inputValue(), '5')
  assert.deepEqual(await page.evaluate(() => window.stock()), [5, 4])
  // Incoming stock changes revalidate an open cart immediately.
  await page.evaluate(async () => { await (await import('/src/db.ts')).db.variants.update(window.v1, { stockQty: 3 }) })
  await page.getByText(/۲ جوره بیشتر از موجودی/).first().waitFor()
  assert.equal(await page.getByRole('button', { name: 'ثبت فروش', exact: true }).isDisabled(), true)
  await page.screenshot({ path: 'qa-sale-availability.png', fullPage: true })
  await qty.fill('1')
  await page.evaluate(async () => {
    const { db } = await import('/src/db.ts')
    await db.variants.update(window.v1, { stockQty: 8 })
    await db.variants.update(window.v2, { stockQty: 8 })
  })
  await page.getByRole('button', { name: /بوت آزمایشی/ }).filter({ has: page.locator('p') }).first().click()
  const choice = page.getByRole('dialog')
  await choice.getByRole('button', { name: '＋', exact: true }).click()
  await page.evaluate(async () => { await (await import('/src/db.ts')).db.variants.update(window.v1, { stockQty: 3 }) })
  await choice.getByText(/تعداد کارتن از باقی‌مانده بیشتر است/).waitFor()
  assert.equal(await choice.getByRole('button', { name: /۲ کارتن \(/ }).isDisabled(), true, 'stale carton count cannot oversell')
  await choice.getByRole('button', { name: '−', exact: true }).click()
  await choice.getByRole('button', { name: /۱ کارتن \(/ }).click()
  assert.equal(await qty.inputValue(), '3')
  assert.equal(await page.getByRole('textbox', { name: 'تعداد بوت آزمایشی 40', exact: true }).inputValue(), '3')
  await page.getByRole('button', { name: /بوت آزمایشی/ }).filter({ has: page.locator('p') }).first().click()
  assert.equal(await choice.getByRole('button', { name: /۱ کارتن \(/ }).isDisabled(), true, 'cannot add the same exhausted carton again')
  await choice.getByRole('button', { name: 'بستن', exact: true }).click()
  await page.getByRole('textbox', { name: 'جستجوی جنس', exact: true }).fill('39')
  assert.equal(await page.getByRole('button', { name: '×۲', exact: true }).isDisabled(), true)
  assert.equal(await page.getByRole('button', { name: '×۳', exact: true }).isDisabled(), true)
  for (const width of [320, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, `no overflow at ${width}`)
  }
  assert.deepEqual(await page.evaluate(() => window.stock()), [3, 8], 'cartons and search never write stock')
  await page.getByRole('button', { name: 'ثبت فروش', exact: true }).click()
  await page.waitForFunction(async () => (await (await import('/src/db.ts')).db.sales.count()) === 1)
  assert.deepEqual(await page.evaluate(() => window.stock()), [0, 5], 'stock changes only at final sale registration')
  assert.equal(await page.evaluate(async () => (await (await import('/src/db.ts')).db.cashMovements.toArray()).reduce((sum, row) => sum + row.amount, 0)), 480)
  assert.deepEqual(browserErrors, [])
  console.log('PASS: live remaining, exhaustion, manual/fractional limits, half-cartons, repeated/stale full cartons, search shortcuts, incoming stock, responsive layout; only final registration changes stock/cash')
} finally { await browser?.close(); server.kill() }
